// No Apple Developer account: ad-hoc sign instead. electron-builder leaves the bundle with
// Electron's original signature, which no longer matches once Info.plist changes, and Apple
// Silicon then reports the downloaded app as "damaged" instead of offering "Open Anyway".
const { execFileSync } = require('child_process');
const path = require('path');

exports.default = async function (context) {
  if (context.electronPlatformName !== 'darwin') return;
  const app = path.join(context.appOutDir, `${context.packager.appInfo.productFilename}.app`);
  execFileSync('codesign', ['--force', '--deep', '--sign', '-', app], { stdio: 'inherit' });
  execFileSync('codesign', ['--verify', '--deep', '--strict', app], { stdio: 'inherit' });
};
